const hay = (x) => `${x.code} ${x.name} ${x.meaning} ${x.use} ${x.headers.join(' ')}`.toLowerCase();

/** Filter by free text (number prefix like "4", "40", "404", or words) and category (1-5 or 0 for all). */
export function search(q, cat = 0) {
  const t = String(q ?? '')
    .trim()
    .toLowerCase();
  const words = t.split(/\s+/).filter(Boolean);
  return CODES.filter((x) => {
    if (cat && Math.floor(x.code / 100) !== cat) return false;
    if (!words.length) return true;
    if (/^\d{1,3}$/.test(t)) return String(x.code).startsWith(t);
    const h = hay(x);
    return words.every((w) => h.includes(w));
  });
}
export const byCode = (n) => CODES.find((x) => x.code === Number(n));
